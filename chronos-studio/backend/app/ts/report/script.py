"""Single-file reproducible .py and optional .R exporters."""

from __future__ import annotations

from typing import Any

from app.ts.report.bundle import ReportBundle
from app.ts.report.utils import safe_json, settings_payload

PY_HEADER = '''"""Chronos Studio reproducible analysis.

Generated by S15. This script replays every stored stage against a running API,
then reads the readiness verdict. It uses the Python standard library only.
Set CHRONOS_BASE_URL if the API is not on http://127.0.0.1:8000/api/v1.
"""
import json
import os
import urllib.error
import urllib.request

BASE = os.environ.get("CHRONOS_BASE_URL", "http://127.0.0.1:8000/api/v1").rstrip("/")
'''


def _settings(bundle: ReportBundle) -> dict[str, Any]:
    return settings_payload(bundle.session)


def render_python(bundle: ReportBundle) -> bytes:
    settings = _settings(bundle)
    data_csv = bundle.data_csv.decode("utf-8", errors="replace")
    body = f'''SETTINGS = json.loads({safe_json(settings)!r})
DATA_CSV = {data_csv!r}


def call(path, payload=None, method="POST", headers=None):
    """One JSON API call; 201 and 200 are both successful."""
    url = BASE + path
    data = None if payload is None else json.dumps(payload, allow_nan=False).encode("utf-8")
    req = urllib.request.Request(url, data=data, method=method, headers={{
        "Content-Type": "application/json",
        **(headers or {{}}),
    }})
    try:
        with urllib.request.urlopen(req, timeout=120) as response:
            raw = response.read().decode("utf-8")
            return json.loads(raw) if raw else {{}}
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")[:800]
        raise SystemExit(f"{{method}} {{path}} failed: HTTP {{exc.code}}: {{detail}}") from exc


def main():
    session = call("/sessions", {{}}, method="POST")
    sid = session["session_id"]
    headers = {{"X-Session-Id": sid}}
    print("session", sid, "seed", SETTINGS.get("seed"))

    if SETTINGS.get("example_id"):
        loaded = call("/data/example", {{"example_id": SETTINGS["example_id"]}}, headers=headers)
    elif DATA_CSV:
        loaded = call("/data/paste",
                      {{"text": DATA_CSV, "mapping": SETTINGS.get("mapping")}},
                      headers=headers)
    else:
        raise SystemExit("No example id or stored table: provide the original CSV to /data/paste.")
    data_hash = loaded.get("dataset", {{}}).get("content_hash", "")
    if SETTINGS.get("content_hash") and data_hash and data_hash != SETTINGS["content_hash"]:
        print("WARNING: data hash differs from the archived session:", data_hash,
              "expected", SETTINGS["content_hash"])

    for step in SETTINGS.get("stage_calls", []):
        path = "/analysis/" + step["path"]
        method = step.get("method", "POST")
        payload = step.get("payload")
        if method == "GET":
            call(path, None, method="GET", headers=headers)
        else:
            call(path, payload or {{}}, method="POST", headers=headers)
        print("replayed", method, path)

    catalog = call("/analysis/catalog", None, method="GET", headers=headers)
    print("catalogue", catalog["scorecard"]["plots"], "plots,",
          catalog["scorecard"]["tables"], "tables")
    call("/export/finalize", {{}}, method="POST", headers=headers)
    status = call("/export/status", None, method="GET", headers=headers)
    print("verdict:", status["scorecard"]["verdict"])
    print("score:", status["scorecard"]["score"], "/", status["scorecard"]["max_score"])
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
'''
    return (PY_HEADER + body).encode("utf-8")


def render_r(bundle: ReportBundle) -> bytes:
    settings = _settings(bundle)
    data_csv = bundle.data_csv.decode("utf-8", errors="replace")
    return f'''# Chronos Studio reproducible analysis (optional R equivalent).
# Requires jsonlite and httr; set CHRONOS_BASE_URL for a non-default API.
if (!requireNamespace("jsonlite", quietly = TRUE) ||
    !requireNamespace("httr", quietly = TRUE)) {{
  stop("Install jsonlite and httr: install.packages(c('jsonlite','httr'))")
}}
BASE <- sub("/+$", "", Sys.getenv("CHRONOS_BASE_URL", "http://127.0.0.1:8000/api/v1"))
SETTINGS <- jsonlite::fromJSON({safe_json(settings)!r})
DATA_CSV <- {data_csv!r}

call <- function(path, payload = NULL, method = "POST", headers = list()) {{
  url <- paste0(BASE, path)
  body <- if (is.null(payload)) NULL else jsonlite::toJSON(payload, auto_unbox = TRUE,
                                                            null = "null", digits = NA)
  response <- if (toupper(method) == "GET")
    httr::GET(url, httr::add_headers(.headers = headers))
  else
    httr::POST(url, body = body, httr::content_type_json(),
               httr::add_headers(.headers = headers))
  httr::stop_for_status(response)
  parsed <- httr::content(response, as = "parsed", type = "application/json")
  if (is.null(parsed)) list() else parsed
}}

session <- call("/sessions", list(), "POST")
sid <- session$session_id
headers <- list(`X-Session-Id` = sid)
cat("session", sid, "seed", SETTINGS$seed, "\\n")
if (!is.null(SETTINGS$example_id) && !is.na(SETTINGS$example_id)) {{
  loaded <- call("/data/example", list(example_id = SETTINGS$example_id), "POST", headers)
}} else if (nzchar(DATA_CSV)) {{
  loaded <- call("/data/paste", list(text = DATA_CSV, mapping = SETTINGS$mapping), "POST", headers)
}} else {{
  stop("No example id or stored table: provide the original CSV to /data/paste.")
}}
for (step in SETTINGS$stage_calls) {{
  path <- paste0("/analysis/", step$path)
  method <- if (!is.null(step$method)) step$method else "POST"
  if (toupper(method) == "GET") call(path, NULL, "GET", headers)
  else call(path, step$payload, "POST", headers)
  cat("replayed", method, path, "\\n")
}}
catalog <- call("/analysis/catalog", NULL, "GET", headers)
cat("catalogue", catalog$scorecard$plots, "plots,", catalog$scorecard$tables, "tables\\n")
call("/export/finalize", list(), "POST", headers)
status <- call("/export/status", NULL, "GET", headers)
cat("verdict:", status$scorecard$verdict, "\\n")
'''.encode("utf-8")


__all__ = ["PY_HEADER", "render_python", "render_r"]
